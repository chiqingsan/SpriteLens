import { test, expect, type Locator, type Page } from '@playwright/test'

async function dragRange(page: Page, slider: Locator, from: number, to: number, grabOffset = 0) {
  await slider.scrollIntoViewIfNeeded()
  const rect = (await slider.boundingBox())!
  const limits = await slider.evaluate(node => ({ min: Number((node as HTMLInputElement).min), max: Number((node as HTMLInputElement).max) }))
  const x = (value: number) => rect.x + 9 + (rect.width - 18) * (value - limits.min) / (limits.max - limits.min)
  await page.mouse.move(x(from) + grabOffset, rect.y + rect.height / 2); await page.mouse.down()
  await page.mouse.move(x(to), rect.y + rect.height / 2, { steps: 5 }); await page.mouse.up()
}

test('特性名称目录无搜索框，名称按原始 ID 提交并可取消', async ({ page }) => {
  await page.setViewportSize({ width: 1440, height: 1000 })
  await page.goto(process.env.SPRITELENS_DEMO_URL!)
  await page.locator('[data-page="pets"]').click()
  await expect(page.locator('#pet-count')).toContainText('命中 40 / 40')
  const search = page.getByRole('searchbox', { name: '搜索特性', exact: true })
  const group = page.locator('details.filter-section').filter({ has: page.locator('summary').filter({ hasText: /^特性/ }) })
  await group.locator('summary').click()
  for (const name of ['同乘', '奇袭', '爱分享']) await expect(group.getByRole('button', { name, exact: true })).toBeVisible()
  await expect(search).toHaveCount(0)
  const button = group.getByRole('button', { name: '爱分享', exact: true })
  const response = page.waitForResponse(response => new URL(response.url()).pathname === '/api/pets' && new URL(response.url()).searchParams.get('speciality') === '1001')
  await button.click()
  expect((await (await response).json()).filters.speciality).toBe(1001)
  await expect(group.locator('summary')).toContainText('爱分享')
  await button.click()
  await expect(group.locator('summary')).toContainText('不限')
  await expect(page.locator('#pet-count')).toContainText('命中 40 / 40')
})

for (const width of [1440, 640]) {
  test(`详情内容、导航、焦点与主题 ${width}px`, async ({ page }) => {
    const errors: string[] = []
    page.on('pageerror', error => errors.push(error.message))
    await page.setViewportSize({ width, height: 900 })
    await page.goto(process.env.SPRITELENS_DEMO_URL!)
    await expect(page.locator('#app')).toBeVisible()
    await page.locator('[data-page="pets"]').click()
    await expect(page.locator('#pet-count')).toContainText('命中 40 / 40')
    await page.locator('#pet-view [data-view="card"]').click()
    const card = page.locator('#pet-grid .pet-card').first()
    await card.focus(); await card.press('Enter')
    const detail = page.locator('#pet-detail')
    await expect(detail).toBeVisible()
    await expect(detail).toHaveAttribute('role', width <= 960 ? 'dialog' : 'region')
    await expect(detail).toContainText('六维对照')
    await expect(detail).toContainText('物种参考范围')
    await expect(detail).toContainText('蛋基础范围')
    await expect(detail.getByRole('button', { name: '关闭详情', exact: true })).toBeFocused()
    if (width <= 960) {
      expect(await page.locator('#page-pets .content-panel').evaluate(node => (node as HTMLElement).inert)).toBe(true)
      await page.keyboard.press('Shift+Tab')
      await expect(detail.locator('[data-locate-team], [data-locate-box]')).toBeFocused()
      await page.keyboard.press('Tab')
      await expect(detail.getByRole('button', { name: '关闭详情', exact: true })).toBeFocused()
    }
    const first = await detail.locator('.detail-sub').textContent()
    await detail.getByRole('button', { name: '下一只', exact: true }).click()
    await expect(detail.locator('.detail-sub')).not.toHaveText(first!)
    await detail.getByRole('button', { name: '上一只', exact: true }).click()
    await expect(detail.locator('.detail-sub')).toHaveText(first!)
    for (const theme of ['miaomiao', 'huohua', 'shuilanlan']) {
      await page.evaluate(value => { document.documentElement.dataset.theme = value }, theme)
      await page.screenshot({ path: `test-results/pet-complete-detail-${width}-${theme}.png` })
      const rect = await detail.boundingBox()
      expect(rect && rect.x >= 0 && rect.x + rect.width <= width + 1).toBeTruthy()
    }
    await page.keyboard.press('Escape')
    await expect(detail).toHaveCount(0)
    await expect(card).toBeFocused()
    expect(await page.locator('#page-pets .content-panel').evaluate(node => (node as HTMLElement).inert)).toBe(false)
    expect(errors).toEqual([])
  })
}

test('双头范围拖动、交叉联动、百分比查询、组合条件与保存失败重试', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.setViewportSize({ width: 1440, height: 1200 })
  await page.goto(process.env.SPRITELENS_DEMO_URL!)
  await expect(page.locator('#app')).toBeVisible()
  await page.locator('[data-page="pets"]').click()
  await expect(page.locator('#pet-count')).toContainText('命中 40 / 40')
  await page.locator('#pet-view [data-view="card"]').click()
  if (await page.locator('#btn-pet-filters').isVisible()) await page.locator('#btn-pet-filters').click()
  await page.locator('#btn-reset-filters').click()
  const heightGroup = page.locator('details.filter-section').filter({ has: page.locator('[data-measure-filter="height_position_min"]') })
  await heightGroup.locator('summary').click()
  const low = page.getByRole('slider', { name: '最低身高', exact: true }), high = page.getByRole('slider', { name: '最高身高', exact: true })
  const upper = await high.evaluate(node => Number((node as HTMLInputElement).max))
  await dragRange(page, low, 0, upper * .3)
  await dragRange(page, high, upper, upper * .7)
  expect(Number(await low.inputValue())).toBeGreaterThan(0)
  expect(Number(await low.inputValue())).toBeLessThan(Number(await high.inputValue()))
  const highBefore = Number(await high.inputValue())
  await dragRange(page, low, Number(await low.inputValue()), upper * .9)
  await expect.poll(async () => await low.inputValue() === await high.inputValue()).toBe(true)
  const point = Number(await high.inputValue())
  await dragRange(page, high, point, upper * .95, 4)
  expect(Number(await high.inputValue())).toBeGreaterThan(point)
  await dragRange(page, low, point, upper * .8, -4)
  expect(Number(await low.inputValue())).toBeLessThan(point)
  expect(Number(await high.inputValue())).toBeGreaterThan(highBefore)
  await low.press('Home'); await high.press('End')
  await expect(low).toHaveAttribute('aria-valuetext', '不限')
  await expect(high).toHaveAttribute('aria-valuetext', '不限')
  const voiceGroup = page.locator('details').filter({ has: page.locator('[data-measure-filter="voice_min"]') })
  await voiceGroup.evaluate(node => { (node as HTMLDetailsElement).open = true })
  await expect(page.locator('[data-measure-filter="voice_min"]')).toHaveValue('-100')
  await expect(page.locator('[data-measure-filter="voice_min"]')).toHaveAttribute('aria-valuetext', '不限')
  const voiceLow = voiceGroup.getByRole('slider', { name: '最低声音', exact: true })
  await dragRange(page, voiceLow, -100, -30)
  await expect(voiceGroup.locator('summary')).toContainText('-30–100dB')
  await voiceLow.press('Home')
  await expect(voiceLow).toHaveAttribute('aria-valuetext', '不限')
  const weightGroup = page.locator('details.filter-section').filter({ has: page.locator('[data-measure-filter="weight_position_min"]') })
  await weightGroup.locator('summary').click()
  for (const group of [heightGroup, weightGroup, voiceGroup]) {
    await expect(group.locator('button, select, output, p')).toHaveCount(0)
    await expect(group.getByRole('slider')).toHaveCount(2)
  }
  await expect(heightGroup.locator('.dual-range-unit span')).toHaveText(['0%', '100%'])
  await expect(weightGroup.locator('.dual-range-unit span')).toHaveText(['0%', '100%'])
  await expect(voiceGroup.locator('.dual-range-unit span')).toHaveText(['-100dB', '100dB'])
  const weightHigh = weightGroup.getByRole('slider', { name: '最高体重', exact: true })
  const weightMax = Number(await weightHigh.inputValue())
  const weightResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/pets' && new URL(response.url()).searchParams.get('weight_position_max') === '99.9')
  await weightHigh.press('ArrowLeft')
  const weightData = await (await weightResponse).json()
  expect(weightMax - Number(await weightHigh.inputValue())).toBeCloseTo(.1, 5)
  expect(weightData.filters.weight_position_max).toBe(Number(await weightHigh.inputValue()))
  await dragRange(page, voiceLow, -100, -30)
  await expect(voiceGroup.locator('.dual-range-unit span')).toHaveText(['-30dB', '100dB'])
  await expect(weightGroup.locator('.dual-range-unit span')).toHaveText(['0%', '99.9%'])
  await page.locator('#pet-filters').screenshot({ path: 'test-results/pet-dual-ranges.png' })
  await weightHigh.press('End')
  await voiceLow.press('Home')
  await page.locator('details').filter({ has: page.locator('#f-level-label') }).locator('summary').click()
  const levelResponse = page.waitForResponse(response => new URL(response.url()).pathname === '/api/pets' && new URL(response.url()).searchParams.get('level_min') === '60')
  await page.locator('#f-level-min').evaluate(node => { (node as HTMLInputElement).value = '60'; node.dispatchEvent(new Event('input', { bubbles: true })) })
  await levelResponse
  await expect(page.locator('#f-level-label')).toHaveText('60 – 60')
  await expect(page.locator('#pet-grid')).toHaveAttribute('aria-busy', 'false')
  await page.locator('.shortcut-section .text-button').first().click()
  await page.locator('#btn-pin-filters').click()
  await expect(page.locator('#shortcut-editor')).toBeVisible()
  await page.locator('#shortcut-name').fill('统一验收快捷条件')
  await page.route('**/api/ui/preferences', route => route.request().method() === 'POST'
    ? route.fulfill({ status: 500, json: { error: '合成保存失败' } }) : route.continue())
  await page.locator('#shortcut-editor button[type="submit"]').click()
  await expect(page.getByRole('alert')).toContainText('合成保存失败')
  await expect(page.locator('#shortcut-editor')).toBeVisible()
  await page.unroute('**/api/ui/preferences')
  await page.locator('#shortcut-editor button[type="submit"]').click()
  await expect(page.locator('#shortcut-editor')).toBeHidden()
  await expect(page.locator('#saved-shortcuts .chip').filter({ hasText: '统一验收快捷条件' })).toHaveCount(1)
  await page.locator('#btn-reset-filters').click()
  await page.locator('#saved-shortcuts .chip').filter({ hasText: '统一验收快捷条件' }).click()
  await expect(page.locator('#f-level-label')).toHaveText('60 – 60')
  await page.locator('.shortcut-section .text-button').first().click()
  await page.locator('#quick-settings-dialog').getByLabel('统一验收快捷条件', { exact: true }).uncheck()
  await page.locator('#quick-settings-dialog').getByRole('button', { name: '保存设置', exact: true }).click()
  await expect(page.locator('#saved-shortcuts .chip').filter({ hasText: '统一验收快捷条件' })).toHaveCount(0)
  await page.locator('#btn-reset-filters').click()
  await page.locator('details').filter({ has: page.locator('#f-egg-groups') }).locator('summary').click()
  await page.locator('#f-egg-groups .chip').first().click()
  await expect(page.locator('#f-egg-groups .chip').first()).toHaveAttribute('aria-pressed', 'true')
  await page.locator('#btn-reset-filters').click()
  const position = heightGroup.locator('[data-measure-filter="height_position_min"]')
  await dragRange(page, position, 0, 25)
  await expect(heightGroup.locator('summary')).toContainText('25–100%')
  await page.locator('#pet-filters').screenshot({ path: 'test-results/pet-filter-improvements.png' })
  await page.locator('#f-gender button').first().click()
  await low.press('Home'); await high.press('End')
  await expect(position).toHaveAttribute('aria-valuetext', '不限')
  await expect(page.locator('#f-gender button').first()).toHaveAttribute('aria-pressed', 'true')
  await expect(heightGroup.locator('summary')).toContainText('不限')
  await page.locator('#btn-reset-filters').click()
  expect(errors).toEqual([])
})
