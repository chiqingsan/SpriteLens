import { test, expect } from '@playwright/test'

test('筛选图标、慢请求计数、快捷设置、来源与日期', async ({ page }) => {
  await page.setViewportSize({ width: 1586, height: 1100 })
  await page.goto(process.env.SPRITELENS_DEMO_URL!)
  await page.locator('[data-page="pets"]').click()
  const count = page.locator('#pet-count'), rail = page.locator('#pet-filters')
  await expect(count).toHaveText('命中 40 / 40 只')
  const stableLayout = await page.evaluate(() => {
    const counter = document.getElementById('pet-count')!, team = document.querySelector<HTMLElement>('.box-teams')!
    const original = [counter.textContent, team.textContent]
    const samples = [['命中 0 / 9 只', '出战'], ['命中 9 / 99 只', '出战 · 9'], ['命中 9999 / 9999 只', '出战 · 99']]
    const positions = samples.map(([countText, teamText]) => {
      counter.textContent = countText; team.textContent = teamText
      return { search: document.getElementById('f-search')!.getBoundingClientRect().x,
        boxes: document.querySelector('.box-tab-strip')!.getBoundingClientRect().x,
        countFits: counter.scrollWidth <= counter.clientWidth, teamFits: team.scrollWidth <= team.clientWidth }
    })
    counter.textContent = original[0]; team.textContent = original[1]
    return positions
  })
  expect(stableLayout.every(item => item.search === stableLayout[0].search && item.boxes === stableLayout[0].boxes && item.countFits && item.teamFits)).toBe(true)
  await expect(page.locator('#pill-pets')).toContainText('精灵：')
  await expect(rail.locator('.detail-filter-head button')).toHaveCount(0)
  await expect(rail.locator('input[type="search"]')).toHaveCount(0)
  const searchRect = (await page.locator('#f-search').boundingBox())!, countRect = (await count.boundingBox())!
  expect(searchRect.x + searchRect.width).toBeLessThan(countRect.x)
  const medals = rail.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^奖牌/ }) })
  await medals.locator('summary').click()
  await expect(medals.locator('.medal-choices button')).toHaveCount(10)
  const quick = rail.locator('#saved-shortcuts')
  const big = medals.getByRole('button', { name: '大块头', exact: true }), voiceMark = medals.getByRole('button', { name: '婉转声', exact: true })
  await big.click(); await voiceMark.click()
  await expect(quick.getByRole('button', { name: '大块头', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await expect(quick.getByRole('button', { name: '婉转声', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await quick.getByRole('button', { name: '大块头', exact: true }).click()
  await expect(big).toHaveAttribute('aria-pressed', 'false')
  await expect(voiceMark).toHaveAttribute('aria-pressed', 'true')
  await voiceMark.click()
  await expect(quick.getByRole('button', { name: '婉转声', exact: true })).toHaveAttribute('aria-pressed', 'false')
  await medals.getByRole('button', { name: '完美无瑕', exact: true }).click()
  const multiple = page.waitForResponse(response => new URL(response.url()).pathname === '/api/pets' && new URL(response.url()).searchParams.get('medals') === '1010,1006')
  await medals.getByRole('button', { name: '王国颂歌', exact: true }).click()
  expect((await (await multiple).json()).filters.medals).toEqual([1006, 1010])
  await page.locator('#btn-reset-filters').click()
  await expect(count).toHaveText('命中 40 / 40 只')
  await expect(medals.locator('.medal-choices img').first()).toBeVisible()
  await expect.poll(() => medals.locator('.medal-choices img').first().evaluate(node => (node as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await medals.locator('summary').click()
  const types = rail.locator('details').filter({ has: page.locator('#f-types') })
  await types.locator('summary').click()
  await expect(types.locator('.chip')).toHaveCount(18)
  await expect(types.getByRole('button', { name: '普', exact: true })).toBeVisible()
  await expect(types.getByRole('button', { name: '机', exact: true })).toBeVisible()
  await expect(types.locator('.chip').first()).toHaveCSS('gap', '8px')
  await expect(types.locator('.filter-type-icon')).toHaveCount(18)
  await expect.poll(() => types.locator('.filter-type-icon').first().evaluate(node => (node as HTMLImageElement).naturalWidth)).toBeGreaterThan(0)
  await types.locator('summary').click()
  const natures = rail.locator('details').filter({ has: page.locator('#f-natures') })
  await natures.locator('summary').click()
  await expect(natures.locator('[data-nature]').last()).toBeVisible()
  await expect(natures.locator('#btn-more-natures')).toHaveCount(0)
  await natures.locator('summary').click()
  await expect(page.locator('.pc-gender use').first()).toHaveAttribute('href', /#gender-(male|female)$/)

  let release!: () => void
  const held = new Promise<void>(resolve => { release = resolve })
  await page.route('**/api/pets?**', async route => { await held; await route.continue() })
  const pending = page.waitForRequest(request => new URL(request.url()).pathname === '/api/pets')
  await rail.locator('#f-gender .chip').first().click(); await pending
  await expect(page.locator('#pet-grid')).toHaveAttribute('aria-busy', 'true')
  await expect(count).toHaveText('命中 40 / 40 只')
  release()
  await expect(page.locator('#pet-grid')).toHaveAttribute('aria-busy', 'false')
  await page.unroute('**/api/pets?**')
  await page.locator('#btn-reset-filters').click()
  await expect(count).toHaveText('命中 40 / 40 只')

  await rail.locator('.shortcut-section .text-button').first().click()
  const dialog = page.getByRole('dialog', { name: '快捷条件设置' })
  await expect(dialog).toBeVisible()
  for (const name of ['大块头', '小不点', '婉转声', '粗嗓门']) await expect(dialog.getByLabel(name, { exact: true })).toBeChecked()
  await expect(dialog.locator('#btn-pin-filters')).toHaveCount(0)
  await expect(dialog.locator('.quick-setting-list').first()).toHaveCSS('display', 'flex')
  await expect(page.locator('.pc-gender .ui-icon').first()).toHaveCSS('width', '14px')
  await expect(page.locator('.pc-gender .ui-icon').first()).toHaveCSS('height', '14px')
  await dialog.getByLabel('孵化', { exact: true }).check()
  await dialog.getByLabel('近3天', { exact: true }).check()
  await dialog.getByLabel('完美无瑕', { exact: true }).check()
  await dialog.locator('.quick-settings-scroll').evaluate(node => { node.scrollTop = 0 })
  await page.screenshot({ path: 'test-results/pet-shortcut-settings.png' })
  await dialog.getByRole('button', { name: '保存设置', exact: true }).click()
  await expect(dialog).toHaveCount(0)
  const saved = rail.locator('#saved-shortcuts')
  const sourceResult = page.waitForResponse(response => new URL(response.url()).pathname === '/api/pets' && new URL(response.url()).searchParams.get('acquisition') === '3')
  await saved.getByRole('button', { name: '孵化', exact: true }).click()
  const sourceData = await (await sourceResult).json()
  expect(sourceData.shown).toBeGreaterThan(0)
  expect(sourceData.pets.every((pet: { catch_way: number }) => pet.catch_way === 3)).toBe(true)
  await saved.getByRole('button', { name: '孵化', exact: true }).click()
  const dateResult = page.waitForResponse(response => new URL(response.url()).pathname === '/api/pets' && new URL(response.url()).searchParams.get('captured_days') === '3')
  await saved.getByRole('button', { name: '近3天', exact: true }).click()
  const dates = rail.locator('details').filter({ has: page.locator('summary').filter({ hasText: /^捕获日期/ }) })
  await expect(dates.locator('summary small')).toHaveText('近 3 天')
  const dateData = await (await dateResult).json()
  expect(dateData.shown).toBeGreaterThan(0)
  expect(dateData.pets.every((pet: { add_time: number }) => pet.add_time > Date.now() / 1000 - 3 * 86400)).toBe(true)
  await page.locator('#btn-reset-filters').click()
  await dates.locator('summary').click()
  await dates.getByRole('button', { name: '一周内', exact: true }).click()
  await expect(dates.locator('summary small')).toHaveText('近 7 天')
  await page.locator('#btn-reset-filters').click()
  await medals.locator('summary').click()
  const perfect = medals.getByRole('button', { name: '完美无瑕', exact: true })
  await perfect.click()
  await expect(saved.getByRole('button', { name: '完美无瑕', exact: true })).toHaveAttribute('aria-pressed', 'true')
  await saved.getByRole('button', { name: '完美无瑕', exact: true }).click()
  await expect(perfect).toHaveAttribute('aria-pressed', 'false')
  await medals.locator('summary').click()
  const voice = rail.locator('details').filter({ has: page.locator('[data-measure-filter="voice_min"]') })
  await voice.locator('summary').click()
  await voice.locator('[data-measure-filter="voice_min"]').press('End')
  await expect(voice.locator('summary small')).toHaveText('100dB')
  await voice.locator('[data-measure-filter="voice_max"]').press('Home')
  await expect(voice.locator('summary small')).toHaveText('-100dB')
  await page.locator('#btn-reset-filters').click()
  await expect(count).toHaveText('命中 40 / 40 只')
  await voice.locator('summary').click()
  await dates.locator('summary').click()
  await medals.locator('summary').click()
  await types.locator('summary').click()
  await page.screenshot({ path: 'test-results/pet-filter-polish.png' })
})
