import { afterEach, expect, it, vi } from 'vitest'
import { usePetAdvancedFilters } from './usePetAdvancedFilters'
afterEach(() => vi.useRealTimers())
it('双头滑杆保留未设置的另一端，交叉联动，回到边界恢复不限', () => {
  vi.useFakeTimers()
  const load = vi.fn(), model = usePetAdvancedFilters(load, vi.fn())
  model.activate()
  model.range('voice', 'min', -20, -100, 100, false)
  expect(model.query()).toMatchObject({ voice_min: -20, voice_max: '' })
  model.range('voice', 'max', -40, -100, 100, false)
  expect(model.query()).toMatchObject({ voice_min: -40, voice_max: -40 })
  model.range('voice', 'min', -100, -100, 100, false)
  model.range('voice', 'max', 100, -100, 100, true)
  vi.runAllTimers()
  expect(model.query()).toMatchObject({ voice_min: '', voice_max: '' })
  expect(load).toHaveBeenCalledTimes(1)
})
it('范围边界与未知输入快速失效旧请求，非法输入不提交', () => {
  vi.useFakeTimers()
  const load = vi.fn(), invalidate = vi.fn(), model = usePetAdvancedFilters(load, invalidate)
  model.activate()
  const input = document.createElement('input'); input.type = 'number'
  input.value = '-1'; model.input('height_position_min', input); vi.runAllTimers()
  expect(invalidate).toHaveBeenCalledTimes(1); expect(load).not.toHaveBeenCalled()
  expect(() => model.query()).toThrow('有效范围')
  input.value = '-100'; model.input('voice_min', input, true)
  expect(model.valid.value).toBe(false)
  input.value = ''; model.input('height_position_min', input, true)
  expect(model.valid.value).toBe(true); expect(load).toHaveBeenCalledTimes(1)
  expect(model.query().voice_min).toBe(-100)
})
it('上下限交换、蛋组模式、恢复与离页取消定时器', () => {
  vi.useFakeTimers()
  const load = vi.fn(), model = usePetAdvancedFilters(load, vi.fn())
  model.activate()
  const input = document.createElement('input'); input.type = 'number'
  input.value = '2'; model.input('weight_position_min', input)
  input.value = '1'; model.input('weight_position_max', input, true)
  expect(model.query()).toMatchObject({ weight_position_min: 1, weight_position_max: 2 })
  expect(model.status.value).toBe('已交换上下限。')
  model.restore({ egg_groups: ['动物组'], egg_mode: 'all', height_position_min: 20 })
  expect(model.query()).toMatchObject({ egg_groups: '动物组', egg_mode: 'all', height_position_min: 20, weight_position_min: '' })
  load.mockClear(); input.value = '1'; model.input('height_position_min', input); model.pause(); vi.runAllTimers()
  expect(load).not.toHaveBeenCalled()
  model.resetAccount(); expect(model.query().egg_groups).toBe(''); expect(model.query().height_position_min).toBe('')
})
